/* 덩어리(part) 정의: ?part=1|2|3 으로 각 활동 페이지가 자기 범위만 보여 준다.
   교과서 4과  : 1=본문 ❶❷❸(L4-1~3) 2=❹❺(L4-4~5) 3=❻❼(L4-6~7)
   모의고사    : 1=22년 11월 2=23년 11월 3=24년 10월
   기록 키     : "<구간>p<번호>:<활동>"  예) L4p1:ko, mockp2:abc
*/
var PARTS={
  L4:{1:['L4-1','L4-2','L4-3'],2:['L4-4','L4-5'],3:['L4-6','L4-7']},
  mock:{1:['2211-29','2211-30','2211-31','2211-32','2211-33'],2:['2211-34','2211-35','2211-36','2211-37','2211-38'],3:['2311-21','2311-23','2311-30','2311-31','2311-32'],4:['2311-33','2311-34','2311-35','2311-36','2311-37'],5:['2311-38','2311-39','2311-40','2311-41','2410-22'],6:['2410-23','2410-24','2410-29','2410-30','2410-33']},
  names:{L4:{1:'본문 ❶~❸',2:'본문 ❹~❺',3:'본문 ❻~❼'},mock:{1:'22년 11월 29~33번',2:'22년 11월 34~38번',3:'23년 11월 21·23·30·31·32번',4:'23년 11월 33~37번',5:'23년 11월 38~41번 · 24년 10월 22번',6:'24년 10월 23·24·29·30·33번'}}
};
var PART=(function(){var m=/[?&]part=([1-7])\b/.exec(location.search);return m?+m[1]:0})();
/* 패시지 id가 이 덩어리에 속하는지. kind: 'L4' 또는 'mock' */
function inPart(kind,pid,part){part=part||PART;if(!part)return true;
  if(kind==='L4')return PARTS.L4[part].indexOf(pid)>=0;
  return PARTS.mock[part].indexOf(String(pid))>=0}
function partKey(kind){return PART?kind+'p'+PART:kind}
